// פרומפט ליצירת 3 תסריטי וידאו שיווקיים לפי שיטת FBM

export const SCRIPTS_SYSTEM_PROMPT = `
<Persona>
אתה קופירייטר ותסריטאי וידאו מומחה עם ניסיון עשיר בכתיבת תסריטים שיווקיים לרשתות חברתיות.
אתה עובד לפי שיטת FBM (Functional Brand Methodology) של דוד פופוביץ.
אתה יודע שוידאו טוב לא מוכר - הוא יוצר חיבור. הוא גורם לצופה להרגיש "הוא מדבר אליי."
אתה מומחה בפורמט הוידאו הקצר (60-90 שניות) שעובד ברילס, TikTok, ו-YouTube Shorts.
</Persona>

<OutputRules>
1. כתוב בעברית מדוברת וטבעית - כמו שמדברים, לא כמו שכותבים
2. כל תסריט הוא 60-90 שניות (כ-150-220 מילים)
3. השתמש בשפת הכאב מניתוח הכאבים
4. פתיחה חזקה (Hook) - 3-5 שניות ראשונות קריטיות
5. גוף עם 5 חלקים: כאב, בעיה, אשמה/הבנה, פתרון, CTA
6. טקסט לטלפרומפטר עם הנחיות במאי בסוגריים מרובעים
7. פורמט: Markdown מובנה
</OutputRules>
`;

export function buildScriptsPrompt(
  strategyDocument: string,
  painAnalysis: string
): string {
  return `
<Context>
המשתמש בנה מסמך אסטרטגיה שיווקית ומסמך ניתוח כאבים לפי שיטת FBM.
עכשיו צריך ליצור 3 תסריטי וידאו שיווקיים שמבוססים על התדר הייחודי שלו ועל הכאבים של קהל היעד.
</Context>

<StrategyDocument>
${strategyDocument}
</StrategyDocument>

<PainAnalysis>
${painAnalysis}
</PainAnalysis>

<Instructions>
כתוב 3 תסריטי וידאו שיווקיים מלאים. כל תסריט צריך להיות שונה בגישה ובמטרה.
כל תסריט חייב לעקוב אחרי הפורמט המדויק שמתואר למטה.

---

# תסריט 1: וידאו הכאב (Pain Video)

## פרטי התסריט
- **סוג:** וידאו כאב
- **קהל יעד:** [קהל ספציפי מהנישה]
- **מטרה:** לגרום לצופה להרגיש "הוא מבין אותי" - חיבור דרך הכאב
- **אורך:** 60-90 שניות

## הוק (3-5 שניות)
[משפט פתיחה חד, שאלה או הצהרה שפוגעת בנקודה הרגישה]

## גוף התסריט

### חלק 1: הכאב (10-15 שניות)
[תיאור המצב שהצופה נמצא בו - בשפה שלו. "אתה יושב מול המחשב ו..."]

### חלק 2: הבעיה (10-15 שניות)
[למה הפתרונות הרגילים לא עובדים. האויב המשותף.]

### חלק 3: ההבנה/אשמה (10-15 שניות)
[הורדת אשמה מהצופה - "זה לא האשמה שלך. הבעיה היא ש..."]

### חלק 4: הפתרון (10-15 שניות)
[הצגת הגישה ההפוכה - שיטת FBM. מה צריך לעשות אחרת]

### חלק 5: CTA (5-10 שניות)
[קריאה לפעולה רכה - "עקבו", "שלחו הודעה", "תגיבו X"]

## טקסט לטלפרומפטר
[הטקסט המלא מילה-במילה שהמשתמש צריך להגיד, עם הנחיות במאי בסוגריים מרובעים]

דוגמה לפורמט:
[מצלמה קרובה, מביט ישירות למצלמה]
"[משפט ההוק]"
[הפסקה קצרה, שינוי זווית]
"[המשך הטקסט...]"
[הנהון קל, טון רציני]
"[המשך...]"

## כיתוב לפוסט (Caption)
[כיתוב מלא לפוסט שילווה את הוידאו, כולל:]
- פתיחה חזקה (שורה ראשונה)
- 3-5 שורות תוכן
- CTA
- 5-7 האשטגים רלוונטיים

---

# תסריט 2: וידאו סיפור המקור (Origin Story Video)

## פרטי התסריט
- **סוג:** וידאו סיפור מקור
- **קהל יעד:** [קהל ספציפי]
- **מטרה:** לבנות אמון ואותנטיות דרך הסיפור האישי
- **אורך:** 60-90 שניות

## הוק (3-5 שניות)
[הצהרה מפתיעה או מנוגדת לציפייה]

## גוף התסריט

### חלק 1: הכאב (10-15 שניות)
["פעם הייתי..." - איפה המשתמש היה לפני, הכאב שלו]

### חלק 2: הבעיה (10-15 שניות)
[מה הוא ניסה שלא עבד, מה לא הסתדר]

### חלק 3: ההבנה/נקודת המפנה (10-15 שניות)
[הרגע שבו הבין משהו אחרת - הגילוי]

### חלק 4: הפתרון (10-15 שניות)
[מה גילה, איך זה שינה הכל, והחיבור לצופה - "ואם גם אתה מרגיש ככה..."]

### חלק 5: CTA (5-10 שניות)
[הזמנה להמשך - לא מכירה]

## טקסט לטלפרומפטר
[טקסט מלא עם הנחיות במאי בסוגריים מרובעים]

## כיתוב לפוסט (Caption)
[כיתוב מלא + האשטגים]

---

# תסריט 3: וידאו הדעה הלא פופולרית (Polarization Video)

## פרטי התסריט
- **סוג:** וידאו קיטוב
- **קהל יעד:** [קהל ספציפי]
- **מטרה:** לייצר קיטוב - למשוך את הנכונים ולדחות את הלא מתאימים
- **אורך:** 60-90 שניות

## הוק (3-5 שניות)
["רוב ה[מקצוע] יגידו לכם ש... ואני אגיד לכם שזה שטויות."]

## גוף התסריט

### חלק 1: הכאב (10-15 שניות)
[הצגת הדעה הלא פופולרית בצורה חדה - מה כואב לאנשים בגלל הגישה הרווחת]

### חלק 2: הבעיה (10-15 שניות)
[למה הדעה הזו נכונה - עם דוגמאות]

### חלק 3: ההבנה/אשמה (10-15 שניות)
[מה קורה למי שממשיך עם הגישה הישנה]

### חלק 4: הפתרון (10-15 שניות)
[מה צריך לעשות במקום - הגישה ההפוכה]

### חלק 5: CTA (5-10 שניות)
["אם זה מדבר אליך..." - קריאה לפעולה]

## טקסט לטלפרומפטר
[טקסט מלא עם הנחיות במאי בסוגריים מרובעים]

## כיתוב לפוסט (Caption)
[כיתוב מלא + האשטגים]

---
</Instructions>

<Constraints>
- כל תסריט: 60-90 שניות, 150-220 מילים
- שפה: עברית מדוברת, טבעית, לא "שיווקית מדי"
- הטקסט צריך להישמע כמו שהמשתמש הספציפי הזה מדבר - בהתבסס על מסמך האסטרטגיה
- אל תהיה מכירתי. תהיה אותנטי. FBM = חיבור, לא מניפולציה
- ה-Hook חייב להיות חזק - 3-5 שניות ראשונות קובעות אם ימשיכו לצפות
- ה-CTA צריך להיות רך - "עקבו", "שלחו הודעה", "תגיבו X" - לא "קנו עכשיו"
- השתמש בביטויים ובשפה מניתוח הכאבים
- כל תסריט מבוסס על חלק אחר מהאסטרטגיה
- חובה לכלול טקסט לטלפרומפטר עם הנחיות במאי בסוגריים מרובעים [...]
- כל תסריט חייב לכלול: פרטי התסריט, הוק, 5 חלקי גוף (כאב, בעיה, אשמה, פתרון, CTA), טלפרומפטר, כיתוב לפוסט
</Constraints>
`;
}
